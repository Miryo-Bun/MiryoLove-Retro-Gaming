export class MissionManager {
  constructor() {
    this.completed = new Set();
    this.current = null;
    this.stage = 0;
  }

  get next() {
    return MISSIONS.find(m => !this.completed.has(m.id)) || null;
  }

  start(m) {
    this.current = { ...m };
    this.stage = 0;
    return this.current;
  }

  complete() {
    if (!this.current) return 0;
    const r = this.current.reward;
    this.completed.add(this.current.id);
    this.current = null;
    this.stage = 0;
    return r;
  }

  check(playerPos, wantedLevel, inVehicle) {
    if (!this.current) return null;
    const m = this.current;
    if (m.type === 'goto' || m.type === 'deliver_car') {
      const t = m.target;
      if (Math.hypot(playerPos.x - t.x, playerPos.z - t.z) < 12) {
        if (m.type === 'deliver_car' && !inVehicle) return null;
        return 'complete';
      }
    }
    if (m.type === 'race' && m.targets) {
      const t = m.targets[this.stage];
      if (t && Math.hypot(playerPos.x - t.x, playerPos.z - t.z) < 12) {
        this.stage++;
        if (this.stage >= m.targets.length) return 'complete';
        return 'stage';
      }
    }
    if (m.type === 'wanted') {
      // Этап 0: набрать розыск; этап 1: уйти от полиции (розыск снова 0)
      if (this.stage === 0 && wantedLevel >= (m.minWanted || 2)) { this.stage = 1; return 'stage'; }
      if (this.stage >= 1 && wantedLevel === 0) return 'complete';
    }
    return null;
  }

  getSave() { return { completed: [...this.completed], currentId: this.current?.id, stage: this.stage }; }
  loadSave(data) {
    if (!data) return;
    this.completed = new Set(data.completed || []);
    if (data.currentId) {
      const m = MISSIONS.find(x => x.id === data.currentId);
      if (m) { this.current = { ...m }; this.stage = data.stage || 0; }
    }
  }
}
